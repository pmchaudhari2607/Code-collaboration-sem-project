-- =============================================================================
-- CodeReviewHub - MySQL 8.0 schema (proposed, v2)
-- Derived from backend/data/seed.js + the services in backend/services.
--
-- STATUS: draft. Not yet executed against a real server - validate it first.
-- TARGET: MySQL 8.0.16+ (CHECK constraints are enforced from that version;
--         the collation utf8mb4_0900_ai_ci does not exist on MariaDB/XAMPP).
--
-- HOW TO RUN: select your DEV database first (it must already exist), then run
-- this file. This file selects no database and drops nothing; the destructive
-- reset lives in reset_dev.sql.
--
-- ID POLICY (v2): every id is a string, VARCHAR(40), ascii_bin (case-sensitive).
--   * existing seed ids are kept as-is ('u1', 'p1', 'v_f2_1', ...)
--   * new rows get '<prefix>_<uuid>' generated by the app, e.g. 'p_3f2c...'
--     (longest prefix 'msg_' + 36-char uuid = 40 chars)
--   * the API returns ids exactly as stored, so the frontend needs no changes.
-- All DATETIME values are UTC (set the connection time zone to 'Z').
-- due_date is a DATE and must be returned as a 'YYYY-MM-DD' string
-- (mysql2 option dateStrings: ['DATE']).
-- =============================================================================

-- =============================================================================
-- 1. users
-- =============================================================================
CREATE TABLE users (
  id            VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  full_name     VARCHAR(100)    NOT NULL,
  username      VARCHAR(30)     NOT NULL,
  email         VARCHAR(255)    NOT NULL,
  password_hash VARCHAR(255)    NOT NULL,          -- bcrypt hash, never plain text
  bio           VARCHAR(500)    NULL,
  created_at    DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_users_username (username),
  UNIQUE KEY uq_users_email (email),
  CONSTRAINT chk_users_username CHECK (username REGEXP '^[A-Za-z0-9_]{3,15}$'),
  CONSTRAINT chk_users_full_name CHECK (CHAR_LENGTH(TRIM(full_name)) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- =============================================================================
-- 2. user_settings (one row per user; replaces the decorative toggles)
-- =============================================================================
CREATE TABLE user_settings (
  user_id            VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  notify_invitations TINYINT(1)      NOT NULL DEFAULT 1,
  notify_reviews     TINYINT(1)      NOT NULL DEFAULT 1,
  notify_tasks       TINYINT(1)      NOT NULL DEFAULT 1,
  notify_versions    TINYINT(1)      NOT NULL DEFAULT 1,
  theme              ENUM('light','dark') NOT NULL DEFAULT 'light',
  updated_at         DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id),
  CONSTRAINT fk_user_settings_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- =============================================================================
-- 3. languages (lookup table: adding C++ later = one INSERT, no code change)
--    'name' is the value the frontend already uses: 'C', 'Java', 'Python'.
-- =============================================================================
CREATE TABLE languages (
  name            VARCHAR(20) NOT NULL,
  file_extensions VARCHAR(50) NOT NULL DEFAULT '',   -- e.g. '.c,.h'
  codemirror_mode VARCHAR(30) NULL,
  is_file_language TINYINT(1) NOT NULL DEFAULT 1,    -- 0 = only valid as a project category ('Mixed')
  is_enabled       TINYINT(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

INSERT INTO languages (name, file_extensions, codemirror_mode, is_file_language) VALUES
  ('C',      '.c,.h', 'text/x-csrc', 1),
  ('Java',   '.java', 'text/x-java', 1),
  ('Python', '.py',   'python',      1),
  ('Mixed',  '',      NULL,          0);

-- =============================================================================
-- 4. projects
-- =============================================================================
CREATE TABLE projects (
  id          VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  owner_id    VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  name        VARCHAR(100)    NOT NULL,
  description VARCHAR(1000)   NOT NULL DEFAULT '',
  visibility  ENUM('public','private') NOT NULL DEFAULT 'public',
  category    VARCHAR(20)     NOT NULL DEFAULT 'Mixed',
  created_at  DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_projects_owner (owner_id),
  KEY idx_projects_visibility_updated (visibility, updated_at),
  KEY idx_projects_name (name),
  CONSTRAINT fk_projects_owner    FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE RESTRICT,
  CONSTRAINT fk_projects_category FOREIGN KEY (category) REFERENCES languages (name) ON UPDATE CASCADE,
  CONSTRAINT chk_projects_name CHECK (CHAR_LENGTH(TRIM(name)) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- =============================================================================
-- 5. project_members (owner row + collaborators + invitations)
--    'viewer' is NOT stored: it is derived (public project + no accepted row).
--    One row per (project, user). Re-inviting a rejected user = UPDATE the row
--    back to 'pending' (not a second INSERT).
-- =============================================================================
CREATE TABLE project_members (
  id         VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  project_id VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  user_id    VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  role       ENUM('owner','collaborator') NOT NULL DEFAULT 'collaborator',
  status     ENUM('pending','accepted','rejected') NOT NULL DEFAULT 'pending',
  invited_by VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
  joined_at  DATETIME        NULL,
  created_at DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_member_project_user (project_id, user_id),
  KEY idx_members_user_status (user_id, status),
  CONSTRAINT fk_members_project    FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_members_user       FOREIGN KEY (user_id)    REFERENCES users (id)    ON DELETE CASCADE,
  CONSTRAINT fk_members_invited_by FOREIGN KEY (invited_by) REFERENCES users (id)    ON DELETE SET NULL,
  CONSTRAINT chk_members_joined CHECK (status <> 'accepted' OR joined_at IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- =============================================================================
-- 6. code_files ('current_code' = working draft; permanent history is in code_versions)
-- =============================================================================
CREATE TABLE code_files (
  id           VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  project_id   VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  file_name    VARCHAR(120)    NOT NULL,
  language     VARCHAR(20)     NOT NULL,
  current_code MEDIUMTEXT      NOT NULL,            -- always supply a value ('' is fine)
  created_by   VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  updated_by   VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
  created_at   DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_files_project_name (project_id, file_name),
  KEY idx_files_created_by (created_by),
  CONSTRAINT fk_files_project    FOREIGN KEY (project_id) REFERENCES projects (id)  ON DELETE CASCADE,
  CONSTRAINT fk_files_language   FOREIGN KEY (language)   REFERENCES languages (name) ON UPDATE CASCADE,
  CONSTRAINT fk_files_created_by FOREIGN KEY (created_by) REFERENCES users (id)     ON DELETE RESTRICT,
  CONSTRAINT fk_files_updated_by FOREIGN KEY (updated_by) REFERENCES users (id)     ON DELETE SET NULL,
  CONSTRAINT chk_files_name CHECK (CHAR_LENGTH(TRIM(file_name)) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- =============================================================================
-- 7. code_versions (immutable snapshots; no UPDATE/DELETE endpoint will exist)
-- =============================================================================
CREATE TABLE code_versions (
  id             VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  file_id        VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  version_number INT UNSIGNED    NOT NULL,
  code           MEDIUMTEXT      NOT NULL,
  note           VARCHAR(255)    NOT NULL DEFAULT '',
  created_by     VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at     DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_versions_file_number (file_id, version_number),
  UNIQUE KEY uq_versions_id_file (id, file_id),       -- lets reviews prove version belongs to file
  KEY idx_versions_created_by (created_by),
  CONSTRAINT fk_versions_file       FOREIGN KEY (file_id)    REFERENCES code_files (id) ON DELETE CASCADE,
  CONSTRAINT fk_versions_created_by FOREIGN KEY (created_by) REFERENCES users (id)      ON DELETE RESTRICT,
  CONSTRAINT chk_versions_number CHECK (version_number >= 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- =============================================================================
-- 8. reviews (line-specific, tied to the exact version that was reviewed)
--    Lifecycle: open -> resolved -> closed.  Reopen => back to 'open'
--    (reopened_at / reopen_count record that it happened).
-- =============================================================================
CREATE TABLE reviews (
  id           VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  file_id      VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  version_id   VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  reviewer_id  VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  line_number  INT UNSIGNED    NOT NULL,
  review_type  ENUM('comment','suggestion','bug','improvement') NOT NULL,
  comment      TEXT            NOT NULL,
  status       ENUM('open','resolved','closed') NOT NULL DEFAULT 'open',
  reopened_at  DATETIME        NULL,
  reopen_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  resolved_by  VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
  resolved_at  DATETIME        NULL,
  closed_by    VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
  closed_at    DATETIME        NULL,
  created_at   DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_reviews_file_version (file_id, version_id),
  KEY idx_reviews_file_status  (file_id, status),
  KEY idx_reviews_reviewer     (reviewer_id),
  KEY idx_reviews_version      (version_id, file_id),
  CONSTRAINT fk_reviews_file     FOREIGN KEY (file_id) REFERENCES code_files (id) ON DELETE CASCADE,
  -- composite FK: the chosen version must belong to the SAME file
  CONSTRAINT fk_reviews_version  FOREIGN KEY (version_id, file_id) REFERENCES code_versions (id, file_id) ON DELETE CASCADE,
  CONSTRAINT fk_reviews_reviewer    FOREIGN KEY (reviewer_id) REFERENCES users (id) ON DELETE RESTRICT,
  CONSTRAINT fk_reviews_resolved_by FOREIGN KEY (resolved_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_reviews_closed_by   FOREIGN KEY (closed_by)   REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT chk_reviews_line    CHECK (line_number >= 1),
  CONSTRAINT chk_reviews_comment CHECK (CHAR_LENGTH(TRIM(comment)) >= 3),
  -- lifecycle invariants (checked on timestamps, not on FK columns)
  CONSTRAINT chk_reviews_open_clean  CHECK (status <> 'open'   OR (resolved_at IS NULL AND closed_at IS NULL)),
  CONSTRAINT chk_reviews_resolved_at CHECK (status = 'open'    OR resolved_at IS NOT NULL),
  CONSTRAINT chk_reviews_closed_at   CHECK (status <> 'closed' OR closed_at IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- =============================================================================
-- 9. tasks (review_id is optional; deleting a review keeps the task)
-- =============================================================================
CREATE TABLE tasks (
  id           VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  project_id   VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  review_id    VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
  created_by   VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  assigned_to  VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
  title        VARCHAR(150)    NOT NULL,
  description  TEXT            NULL,
  status       ENUM('todo','in_progress','completed') NOT NULL DEFAULT 'todo',
  priority     ENUM('low','medium','high') NOT NULL DEFAULT 'medium',
  due_date     DATE            NULL,
  completed_at DATETIME        NULL,
  created_at   DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_tasks_project_status  (project_id, status),
  KEY idx_tasks_assignee_status (assigned_to, status),
  KEY idx_tasks_due_date        (due_date),
  KEY idx_tasks_review          (review_id),
  KEY idx_tasks_created_by      (created_by),
  CONSTRAINT fk_tasks_project  FOREIGN KEY (project_id)  REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_tasks_review   FOREIGN KEY (review_id)   REFERENCES reviews (id)  ON DELETE SET NULL,
  CONSTRAINT fk_tasks_creator  FOREIGN KEY (created_by)  REFERENCES users (id)    ON DELETE RESTRICT,
  CONSTRAINT fk_tasks_assignee FOREIGN KEY (assigned_to) REFERENCES users (id)    ON DELETE SET NULL,
  CONSTRAINT chk_tasks_title CHECK (CHAR_LENGTH(TRIM(title)) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- =============================================================================
-- 10. notifications
--     reference_id (string id) points at a different table depending on 'type':
--       invitation -> project_members.id | review/resolution -> reviews.id
--       task -> tasks.id | version -> code_versions.id
--     (polymorphic, so it cannot be a real FK; the API resolves a 'link').
-- =============================================================================
CREATE TABLE notifications (
  id           VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  user_id      VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  actor_id     VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
  project_id   VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
  type         ENUM('invitation','review','resolution','task','version') NOT NULL,
  reference_id VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
  message      VARCHAR(500)    NOT NULL,
  is_read      TINYINT(1)      NOT NULL DEFAULT 0,
  created_at   DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_notifications_user_read_created (user_id, is_read, created_at),
  KEY idx_notifications_project (project_id),
  CONSTRAINT fk_notifications_user    FOREIGN KEY (user_id)    REFERENCES users (id)    ON DELETE CASCADE,
  CONSTRAINT fk_notifications_actor   FOREIGN KEY (actor_id)   REFERENCES users (id)    ON DELETE SET NULL,
  CONSTRAINT fk_notifications_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- =============================================================================
-- 11. activity_log (feeds dashboard "Recent Activity" and the project Activity tab)
-- =============================================================================
CREATE TABLE activity_log (
  id          VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  project_id  VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  user_id     VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  action_text VARCHAR(255)    NOT NULL,
  created_at  DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_activity_project_created (project_id, created_at),
  KEY idx_activity_user (user_id),
  CONSTRAINT fk_activity_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_activity_user    FOREIGN KEY (user_id)    REFERENCES users (id)    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- =============================================================================
-- 12. messages (project chat; you already have routes/services for it)
-- =============================================================================
CREATE TABLE messages (
  id         VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  project_id VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  sender_id  VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  content    VARCHAR(2000)   NOT NULL,
  created_at DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_messages_project_created (project_id, created_at),
  KEY idx_messages_sender (sender_id),
  CONSTRAINT fk_messages_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
  CONSTRAINT fk_messages_sender  FOREIGN KEY (sender_id)  REFERENCES users (id)    ON DELETE RESTRICT,
  CONSTRAINT chk_messages_content CHECK (CHAR_LENGTH(TRIM(content)) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

